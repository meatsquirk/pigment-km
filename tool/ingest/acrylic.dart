// Offline ingest step 2 (DATA-5): build the shipped acrylic pigment artifact
// from the Golden/RIT drawdown spectra.
//
// Reads `tool/ingest/raw/rit/golden_spectra.csv` (produced by extract_golden.py
// from the archived Golden/RIT workbook; Okumura 2005, Berns/RIT Art Spectral
// Database, redistribution per the permission held — gate G-3) and writes:
//
//   • assets/pigments/acrylic.json  — the shipped, runtime-loadable K,S artifact
//   • test/acceptance/harness/acrylic_published_data.dart — the generated map of
//     each paint's published D65/10° L*a*b* (the AC-7 round-trip yardstick)
//
// K,S convention (design §4.1; G-3 note; DATA-5 / G-5 decision 2026-10-19):
// the dataset ships a turnkey K/S column that is the simple Kubelka–Munk
// inversion of the measured drawdown reflectance (no Saunderson baked in — the
// K/S column and the raw reflectance render to the same colour). We store the
// two-constant form under the standard single-measurement S-normalization
// S ≡ 1, K = K/S, taking K = kmFunction(measured R) directly from the engine's
// own K–M function so kmReflectance(K/S) reproduces the measured reflectance
// exactly. The AC-7 round-trip (`spectrumToColour(kmReflectance(K/S))`) then
// renders the measured reflectance through the 10° colour pipeline and matches
// the dataset's published D65/10° Lab — observer-matched by COLOR-4. The
// Saunderson k1,k2 do not enter this single-paint round-trip (G-5 stays open
// only for mixing fidelity, FORWARD-3, and the oil observer, DATA-6).
//
// opacity: the S ≡ 1 turnkey normalization carries no scattering magnitude, so a
// paint's true hiding power is not separable from this dataset; the opaque R∞
// K–M model treats every paint at complete hiding, so opacity is recorded as
// 1.0 (metadata only — no colour/mixing maths reads it; a documented gap).
// pigmentIndex: this dataset provides Prod # + Name but no Colour Index generic
// name, so pigmentIndex is '' (empty); the Prod # is carried in sourceRef.
//
// Run from the repo root: dart run tool/ingest/acrylic.dart

import 'dart:io';
import 'dart:typed_data';

import 'package:pigment_km/pigment_km.dart';

const String _csvPath = 'tool/ingest/raw/rit/golden_spectra.csv';
const String _artifactPath = 'assets/pigments/acrylic.json';
const String _publishedPath = 'test/acceptance/harness/acrylic_published_data.dart';

typedef AcrylicRow = ({String prod, String name, double l, double a, double b, List<double> r});

/// Parses the extractor's CSV (header + 78 rows: prod,name,L,a,b,R400..R700).
List<AcrylicRow> parseCsv(String csv) {
  final lines = csv.trim().split('\n');
  final rows = <AcrylicRow>[];
  for (final line in lines.skip(1)) {
    final f = line.split(',');
    rows.add((
      prod: f[0],
      name: f[1],
      l: double.parse(f[2]),
      a: double.parse(f[3]),
      b: double.parse(f[4]),
      r: [for (var i = 5; i < 5 + CanonicalGrid.bins; i++) double.parse(f[i])],
    ));
  }
  return rows;
}

/// The stable internal id slug for a paint name: `acrylic.<snake_case>`.
String slugId(String name) {
  final slug = name
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
      .replaceAll(RegExp(r'^_+|_+$'), '');
  return 'acrylic.$slug';
}

/// Builds the acrylic pigment artifact from the parsed rows. Pure (no IO) so the
/// mapping is unit-testable.
PigmentArtifact buildArtifact(List<AcrylicRow> rows) {
  final seen = <String>{};
  final paints = <Pigment>[];
  for (final row in rows) {
    final id = slugId(row.name);
    if (!seen.add(id)) {
      throw StateError('duplicate paint id $id from name "${row.name}"');
    }
    final reflectance = CanonicalGrid.checkLength(Float32List.fromList(row.r));
    // Two-constant K,S under S ≡ 1: K = K/S = kmFunction(measured reflectance).
    final k = kmFunction(reflectance);
    final s = Float32List.fromList(
        List<double>.filled(CanonicalGrid.bins, 1.0));
    paints.add(Pigment(
      id: id,
      name: row.name,
      pigmentIndex: '',
      medium: Medium.acrylic,
      k: k,
      s: s,
      opacity: 1.0,
      provenance: Provenance.calculated,
      sourceRef: 'golden-rit:hb-10mil-drawdowns-over-white/${row.prod}',
    ));
  }
  return PigmentArtifact(
    version: PigmentArtifactCodec.currentVersion,
    medium: Medium.acrylic,
    pigments: paints,
  );
}

/// The generated Dart source for the published-Lab yardstick map.
String buildPublishedDart(List<AcrylicRow> rows) {
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/ingest/acrylic.dart — do not edit by hand.')
    ..writeln('// Regenerate: dart run tool/ingest/acrylic.dart')
    ..writeln('//')
    ..writeln('// Each acrylic paint id mapped to its published CIE L*a*b* under')
    ..writeln('// D65 / the CIE 1964 10° observer, as shipped in the Golden/RIT')
    ..writeln('// drawdown dataset (Okumura 2005; Berns/RIT; G-3 permission). This is')
    ..writeln("// the AC-7 round-trip yardstick — the test's independent published")
    ..writeln('// colour for each paint, converted to a ColourValue via the harness.')
    ..writeln()
    ..writeln('/// Published D65/10° L*a*b* per acrylic paint id (AC-7). Generated.')
    ..writeln('const Map<String, ({double l, double a, double b})> acrylicPublishedLab = {');
  for (final row in rows) {
    b.writeln("  '${slugId(row.name)}': (l: ${row.l}, a: ${row.a}, b: ${row.b}),");
  }
  b.writeln('};');
  return b.toString();
}

void main() {
  final rows = parseCsv(File(_csvPath).readAsStringSync());
  final artifact = buildArtifact(rows);
  File(_artifactPath)
      .writeAsStringSync('${PigmentArtifactCodec.encode(artifact)}\n');
  File(_publishedPath).writeAsStringSync(buildPublishedDart(rows));
  stdout.writeln('wrote $_artifactPath (${artifact.pigments.length} paints)');
  stdout.writeln('wrote $_publishedPath');
}
